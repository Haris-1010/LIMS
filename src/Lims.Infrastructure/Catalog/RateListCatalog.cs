    public static string SampleTypeCode(string specimen)
    {
        var s = specimen.ToUpperInvariant();
        if (s.Contains("24 HRS URINE")) return "URINE-24H";
        if (s.Contains("URINE")) return "URINE";
        if (s.Contains("STOOL")) return "STOOL";
        if (s.Contains("SWAB")) return "SWAB";
        if (s.Contains("SPUTUM")) return "SPUTUM";
        if (s.Contains("CSF")) return "CSF";
        if (s.Contains("CITRATE") || s.Contains("PT VIAL")) return "PL-CIT";
        if (s.Contains("FLUORIDE")) return "PL-FLU";
        if (s.Contains("HEPARIN")) return "PL-HEP";
        if (s.Contains("EDTA")) return "WB-EDTA";
        return "SERUM";
    }
